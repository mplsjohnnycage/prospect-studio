import {chromium} from "playwright";
const browser=await chromium.launch({headless:true,args:["--no-sandbox","--disable-dev-shm-usage"]});
const page=await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1});
const errors=[];
page.on("pageerror",error=>errors.push(error.message));
page.on("console",msg=>{if(msg.type()==="error")errors.push("CONSOLE "+msg.text().slice(0,200))});
await page.goto("http://127.0.0.1:3000/",{waitUntil:"domcontentloaded",timeout:30000});
await page.waitForTimeout(3500);
await page.screenshot({path:"/tmp/prospect-desktop.png",fullPage:true});
console.log("DESKTOP",await page.title(),"header:",(await page.locator("body").innerText()).slice(0,400).replace(/\n/g," | "));
const calendarButton=page.getByRole("button",{name:/Calendar/i}).first();
await calendarButton.click();
await page.waitForTimeout(1500);
await page.screenshot({path:"/tmp/prospect-calendar.png",fullPage:true});
console.log("CALENDAR",await page.locator("body").innerText().then(s=>s.slice(0,400).replace(/\n/g," | ")));
const studioButton=page.getByRole("button",{name:/Studio/i}).first();
await studioButton.click();
await page.waitForTimeout(800);
await page.screenshot({path:"/tmp/prospect-studio.png",fullPage:true});
console.log("STUDIO",await page.locator("body").innerText().then(s=>s.slice(0,400).replace(/\n/g," | ")));
const mobile=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1});
mobile.on("pageerror",error=>errors.push("MOBILE "+error.message));
await mobile.goto("http://127.0.0.1:3000/",{waitUntil:"domcontentloaded",timeout:30000});
await mobile.waitForTimeout(2000);
await mobile.screenshot({path:"/tmp/prospect-mobile.png",fullPage:true});
console.log("MOBILE",await mobile.locator("body").innerText().then(s=>s.slice(0,300).replace(/\n/g," | ")));
console.log("JS_ERRORS",JSON.stringify(errors.slice(0,20)));
await browser.close();
if(errors.some(x=>/TypeError|ReferenceError|Hydration|Unhandled|not defined|Failed to fetch|Failed to load resource/i.test(x)))process.exitCode=1;
